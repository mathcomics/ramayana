// A layout template for sketching panels by hand (Inkscape): the panel's
// page rectangle, the three rows' ground lines, and three male figures for
// scale, one standing in each row (front, mid, back).
//
//   node tools/layout-template.mjs [size]     # default 1 → layouts/template-1.svg
//
// Layers: `page` (the panel rectangle), `guide` (row ground lines and
// labels), `figures` (locked), and an empty `sketch` layer to draw in.
// Sizes and rows as in docs/design/panels.md.

import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { renderPanel, panelHeight, ROWS, SCREEN } from '../src/scene.js';
import { loadAssets, root } from './lib.mjs';

const size = Number(process.argv[2] ?? 1);
const W = SCREEN.w, H = panelHeight({ size });
const assets = loadAssets();

// one male figure per row, so each row's scale can be read off
const figs = [
  { who: 'raxas_m1', pose: 'stand', facing: 'right', at: 0.78, row: 'back' },
  { who: 'lakshman', pose: 'stand', facing: 'right', at: 0.5, row: 'mid' },
  { who: 'rama', pose: 'stand', facing: 'right', at: 0.22, row: 'front' },
];
const r = renderPanel({ size, ground: '#ffffff', figures: figs }, assets, { id: 'layout' });
// the figures only: drop the panel's own <svg> wrapper and ground rectangle
const inner = r.svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/^<rect[^>]*\/>/, '');

const k = H / 540;                                // rows are set for a 0.75 panel
const guide = Object.entries(ROWS).map(([name, row]) => {
  const y = (H * (1 - row.ground)).toFixed(1);
  const man = (row.unit * k * 7.5).toFixed(0);
  return `<line x1="0" x2="${W}" y1="${y}" y2="${y}" stroke="#7aa6c2" stroke-width="0.8" stroke-dasharray="4 3"/>` +
    `<text x="${W - 4}" y="${(Number(y) + 9).toFixed(1)}" font-family="sans-serif" font-size="9" fill="#5b88a4" text-anchor="end">${name} row · head ${(row.unit * k).toFixed(0)} · man ≈ ${man}</text>`;
}).join('\n    ');

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Layout template, panel size ${size} (${W} × ${H}, one phone screen = 360 × 720).
     Generated by tools/layout-template.mjs. Sketch in the "sketch" layer;
     the figures show the scale of a man in each row (front, mid, back). -->
<svg xmlns="http://www.w3.org/2000/svg"
     xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"
     xmlns:sodipodi="http://sodipodi.sourceforge.net/DTD/sodipodi-0.dtd"
     width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <g inkscape:label="page" inkscape:groupmode="layer" id="page" sodipodi:insensitive="true">
    <rect x="0" y="0" width="${W}" height="${H}" fill="#ffffff" stroke="#333333" stroke-width="1.5"/>
  </g>
  <g inkscape:label="guide" inkscape:groupmode="layer" id="guide" sodipodi:insensitive="true">
    ${guide}
  </g>
  <g inkscape:label="figures" inkscape:groupmode="layer" id="figures" sodipodi:insensitive="true">
    ${inner}
  </g>
  <g inkscape:label="sketch" inkscape:groupmode="layer" id="sketch"/>
</svg>
`;
mkdirSync(join(root, 'layouts'), { recursive: true });
const out = join(root, 'layouts', `template-${size}.svg`);
writeFileSync(out, svg);
console.log(out);
