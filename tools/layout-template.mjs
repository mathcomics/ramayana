// A layout template for sketching panels by hand (Inkscape): the panel's
// page rectangle and three simple standing men, one per row (front, mid,
// back), at the height a man has in that row.
//
//   node tools/layout-template.mjs [size] [shot]   # → layouts/<size>-<shot>.svg (default 0.75 far)
//
// Shots (src/scene.js SHOTS): far (small figures, deep rows), wide (whole
// figures, bigger), mid (close, the front row cut at the thighs; no back
// man). The artist's own 0.75-wide and 0.75-mid are the originals of
// those rows; don't overwrite them.
//
// No layers: a locked group `page` (the rectangle and the rows' ground
// lines).
// Each man is a plain group (head, body, legs) outside any layer, so it
// can be moved, copied and scaled freely. Sizes and rows as in
// docs/design/panels.md.

import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { panelHeight, SHOTS, SCREEN, SIZES } from '../src/scene.js';
import { root } from './lib.mjs';

const size = Number(process.argv[2] ?? 0.75);
if (!SIZES.includes(size)) throw new Error(`size ${size}: one of ${SIZES.join(', ')}`);
const shotName = process.argv[3] ?? 'far';
const ROWS = SHOTS[shotName];
if (!ROWS) throw new Error(`shot ${shotName}: one of ${Object.keys(SHOTS).join(', ')}`);
const W = SCREEN.w, H = panelHeight({ size });
const k = H / 540;                                // rows are set for a 0.75 panel
const MAN = 7.5;                                  // a man's height in head-units
const f = (v) => +v.toFixed(1);

// a simple man, feet at (x, y), head-unit u: head, body, legs
function man(id, x, y, u) {
  const top = y - MAN * u;
  const head = `<circle cx="${f(x)}" cy="${f(top + 0.5 * u)}" r="${f(0.5 * u)}"/>`;
  const body = `<rect x="${f(x - 0.65 * u)}" y="${f(top + 1.25 * u)}" width="${f(1.3 * u)}" height="${f(2.9 * u)}" rx="${f(0.4 * u)}"/>`;
  const legs = `<rect x="${f(x - 0.45 * u)}" y="${f(top + 3.9 * u)}" width="${f(0.9 * u)}" height="${f(3.6 * u)}" rx="${f(0.25 * u)}"/>`;
  return `  <g id="${id}" inkscape:label="${id}" fill="#a8a29a">\n    ${head}\n    ${body}\n    ${legs}\n  </g>`;
}

// where each man stands (as in the artist's layouts); the mid shot has no back man
const AT = { far: { back: 0.78, mid: 0.5, front: 0.22 }, wide: { back: 0.47, mid: 0.78, front: 0.21 }, mid: { mid: 0.78, front: 0.31 } };
const at = AT[shotName] || AT.far;
const lines = [], men = [];
for (const name of ['back', 'mid', 'front']) {
  const row = ROWS[name], y = H * (1 - row.ground);
  if (y <= H) lines.push(`<line x1="0" x2="${W}" y1="${f(y)}" y2="${f(y)}" stroke="#c9c4bc" stroke-width="0.8" stroke-dasharray="4 3"/>`);
  if (at[name] != null) men.push(man(`man-${name}`, W * at[name], y, row.unit * k));
}

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Layout template, panel size ${size} (${W} × ${H}; one phone screen = 360 × 720), shot ${shotName}.
     Generated by tools/layout-template.mjs. A man standing in each row
     (front, mid, back) for scale. -->
<svg xmlns="http://www.w3.org/2000/svg"
     xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"
     xmlns:sodipodi="http://sodipodi.sourceforge.net/DTD/sodipodi-0.dtd"
     width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <g inkscape:label="page" id="page" sodipodi:insensitive="true">
    <rect x="0" y="0" width="${W}" height="${H}" fill="#ffffff" stroke="#333333" stroke-width="1.5"/>
    ${lines.join('\n    ')}
  </g>
${men.join('\n')}
</svg>
`;
mkdirSync(join(root, 'layouts'), { recursive: true });
const out = join(root, 'layouts', `${size}-${shotName}.svg`);
writeFileSync(out, svg);
console.log(out);
