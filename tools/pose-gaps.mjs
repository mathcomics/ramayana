// Which poses the story asks for, and which are missing.
//
//   node tools/pose-gaps.mjs            # writes docs/issues/missing-poses.md
//   node tools/pose-gaps.mjs --scenes   # also prints candidate poses per scene
//   node tools/pose-gaps.mjs 04         # only section 04 (with --scenes)
//
// Reads the "what we see" column of manuscript/scenes.md, finds the story
// moments (tags) by the words in data/pose-index.json, and counts how many
// scenes ask for each tag against the poses that cover it. Panel `needs`
// that name a pose are counted too. See docs/design/pose-picking.md.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { root, json } from './lib.mjs';

const args = process.argv.slice(2);
const showScenes = args.includes('--scenes');
const only = args.find((a) => /^\d\d$/.test(a));

const index = json('data/pose-index.json');
const poseNames = json('data/poses.json').poses.map((p) => p.name);

// --- scenes: | id | size | what we see | cast | props |
const scenes = readFileSync(join(root, 'manuscript/scenes.md'), 'utf8').split('\n')
  .filter((l) => /^\|\s*\d\d\.\d\d\s*\|/.test(l))
  .map((l) => { const c = l.split('|').map((s) => s.trim()); return { id: c[1], what: c[3] }; });

const notWords = new Set(index.notWords || []);
const stems = Object.entries(index.tags).map(([tag, t]) => [tag, t.words.map((w) => w.toLowerCase().trim())]);
// A tag matches when a word of the line starts with one of its stems
// (or the line contains a stem of several words). Bold names and the
// index's notWords (Sita, ready, …) never match.
export function tagsOf(text) {
  const t = text.replace(/\*\*[^*]+\*\*/g, ' ').toLowerCase();
  const words = (t.match(/[a-z]+/g) || []).filter((w) => !notWords.has(w));
  const flat = ` ${words.join(' ')} `;
  return stems.filter(([, ws]) => ws.some((w) => (/[^a-z]/.test(w) ? flat.includes(` ${w.replace(/[^a-z ]/g, '').trim()} `) : words.some((x) => x.startsWith(w))))).map(([tag]) => tag);
}
const posesFor = (tag) => Object.entries(index.poses).filter(([, e]) => e.use.includes(tag)).map(([n]) => n);
const wantedFor = (tag) => Object.entries(index.wanted).filter(([, w]) => w.use.includes(tag)).map(([n]) => n);

const count = {}, where = {};
for (const s of scenes) for (const tag of tagsOf(s.what)) {
  count[tag] = (count[tag] || 0) + 1;
  (where[tag] ||= []).push(s.id);
}

// --- panel needs that ask for a pose
const needs = [];
const pdir = join(root, 'panels');
if (existsSync(pdir)) for (const sec of readdirSync(pdir)) {
  for (const f of readdirSync(join(pdir, sec)).filter((x) => x.endsWith('.json'))) {
    const p = JSON.parse(readFileSync(join(pdir, sec, f), 'utf8'));
    for (const n of p.needs || []) if (/^pose:/i.test(n)) needs.push(`${f.replace('.json', '')}: ${n.replace(/^pose:\s*/i, '')}`);
    for (const fig of p.figures || []) if (fig.pose && !poseNames.includes(fig.pose)) needs.push(`${f.replace('.json', '')}: unknown pose "${fig.pose}"`);
  }
}

// --- report
const rows = Object.keys(index.tags)
  .map((tag) => ({ tag, n: count[tag] || 0, poses: posesFor(tag), wanted: wantedFor(tag) }))
  .sort((a, b) => (a.poses.length > 0) - (b.poses.length > 0) || b.n - a.n);

const line = (r) => `| ${r.tag} | ${r.n} | ${r.poses.join(', ') || '**none**'} | ${r.wanted.join(', ')} |`;
let md = `# Missing poses\n\nGenerated by \`node tools/pose-gaps.mjs\` from \`manuscript/scenes.md\`,\n` +
  `\`data/pose-index.json\` and the panels' \`needs\`. Do not edit by hand; rerun it\n` +
  `after changing poses, the index or the scenes. How poses are picked:\n\`docs/design/pose-picking.md\`.\n\n` +
  `${scenes.length} scenes, ${poseNames.length} poses, ${Object.keys(index.wanted).length} wanted.\n\n` +
  `## Story moments\n\nScenes = scene lines whose words call for the moment. Moments with no pose come first.\n\n` +
  `| moment | scenes | poses | wanted |\n|---|---|---|---|\n${rows.map(line).join('\n')}\n\n` +
  `## Wanted poses, in order\n\n| pose | what | scenes (its busiest moment) | until it exists |\n|---|---|---|---|\n` +
  Object.entries(index.wanted).map(([n, w]) => `| ${n} | ${w.desc} | ${w.use.map((t) => count[t] || 0).reduce((a, b) => Math.max(a, b), 0)} | ${w.until} |`).join('\n') +
  `\n\n## Asked for by panels\n\n${needs.length ? needs.map((n) => `- ${n}`).join('\n') : '(none)'}\n`;

writeFileSync(join(root, 'docs/issues/missing-poses.md'), md);
console.log('docs/issues/missing-poses.md');
for (const r of rows.filter((r) => !r.poses.length)) console.log(`  no pose: ${r.tag} (${r.n} scenes)`);

if (showScenes) {
  console.log('');
  for (const s of scenes.filter((s) => !only || s.id.startsWith(only))) {
    const tags = tagsOf(s.what);
    const cands = [...new Set(tags.flatMap(posesFor))];
    const want = [...new Set(tags.flatMap(wantedFor))];
    console.log(`${s.id}  ${s.what.replace(/\*\*/g, '').slice(0, 90)}`);
    console.log(`       moments: ${tags.join(', ') || '-'}`);
    console.log(`       poses:   ${cands.join(', ') || 'stand'}${want.length ? `   (wanted: ${want.join(', ')})` : ''}`);
  }
}
