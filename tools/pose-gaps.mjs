// Which poses the story asks for, and which are missing.
//
//   node tools/pose-gaps.mjs            # writes docs/issues/missing-poses.md
//   node tools/pose-gaps.mjs --scenes   # also prints candidate bases and gestures per beat
//   node tools/pose-gaps.mjs 04         # only chapter 04 (with --scenes)
//
// Reads the beats (bullets under each "## N." chapter) of
// manuscript/scenes.md, finds the story moments (tags) by the words in
// data/poses.json, and counts how many beats ask for each tag against
// the bases and gestures that carry it (their `use`): a pose for the
// moment is one of those bases with any gesture, or one of those
// gestures on any base. Panel `needs` that name a pose, and poses with an
// unknown half, are listed too. See docs/design/pose-picking.md.

import { loadPoseData, loadChapters, loadSections, writeOut } from './lib.mjs';
import { splitPoseName } from '../src/compose.js';

const args = process.argv.slice(2);
const showScenes = args.includes('--scenes');
const only = args.find((a) => /^\d\d$/.test(a));

const index = loadPoseData();

// --- beats: "- ..." bullets (with their wrapped lines) under "## N. Title"
const scenes = loadChapters().flatMap((c) => c.beats.map((what) => ({ id: String(c.n).padStart(2, '0'), what })));

const notWords = new Set(index.notWords || []);
const stems = Object.entries(index.tags).map(([tag, t]) => [tag, t.words.map((w) => w.toLowerCase().trim())]);
// A tag matches when a word of the line starts with one of its stems
// (or the line contains a stem of several words). Bold names and the
// index's notWords (Sita, ready, …) never match.
function tagsOf(text) {
  const t = text.replace(/\*\*[^*]+\*\*/g, ' ').toLowerCase();
  const words = (t.match(/[a-z]+/g) || []).filter((w) => !notWords.has(w));
  const flat = ` ${words.join(' ')} `;
  return stems.filter(([, ws]) => ws.some((w) => (/[^a-z]/.test(w) ? flat.includes(` ${w.replace(/[^a-z ]/g, '').trim()} `) : words.some((x) => x.startsWith(w))))).map(([tag]) => tag);
}
const halvesFor = (kind, tag) => Object.entries(index[kind]).filter(([, e]) => e.use.includes(tag)).map(([n]) => n);
const wantedFor = (tag) => Object.entries(index.wanted).filter(([, w]) => w.use.includes(tag)).map(([n]) => n);

const count = {}, where = {};
for (const s of scenes) for (const tag of tagsOf(s.what)) {
  count[tag] = (count[tag] || 0) + 1;
  (where[tag] ||= []).push(s.id);
}

// --- panel needs that ask for a pose, and poses with an unknown half
const needs = [];
for (const { panels } of loadSections()) for (const { id, def: p } of panels) {
  for (const n of p.needs || []) if (/^pose:/i.test(n)) needs.push(`${id}: ${n.replace(/^pose:\s*/i, '')}`);
  for (const fig of p.figures || []) {
    if (!fig.pose) continue;
    const [b, g] = splitPoseName(fig.pose);
    if (!index.bases[b]) needs.push(`${id}: unknown pose "${fig.pose}" (no base "${b}")`);
    else if (!index.gestures[g]) needs.push(`${id}: unknown pose "${fig.pose}" (no gesture "${g}")`);
  }
}

// --- report
const rows = Object.keys(index.tags)
  .map((tag) => ({ tag, n: count[tag] || 0, bases: halvesFor('bases', tag), gestures: halvesFor('gestures', tag), wanted: wantedFor(tag) }))
  .map((r) => ({ ...r, any: r.bases.length + r.gestures.length > 0 }))
  .sort((a, b) => a.any - b.any || b.n - a.n);

const line = (r) => `| ${r.tag} | ${r.n} | ${r.bases.join(', ') || (r.any ? '' : '**none**')} | ${r.gestures.join(', ')} | ${r.wanted.join(', ')} |`;
const md = `# Missing poses\n\nGenerated by \`node tools/pose-gaps.mjs\` from \`manuscript/scenes.md\`,\n` +
  `\`data/bases.json\`, \`data/gestures.json\`, \`data/poses.json\` and the panels' \`needs\`.\n` +
  `Do not edit by hand; rerun it after changing bases, gestures, the tags or the\nscenes. How poses are picked: \`docs/design/pose-picking.md\`.\n\n` +
  `${scenes.length} beats, ${Object.keys(index.bases).length} bases, ${Object.keys(index.gestures).length} gestures, ${Object.keys(index.wanted).length} wanted.\n\n` +
  `## Story moments\n\nBeats = chapter-brief beats whose words call for the moment (the id is the\n` +
  `chapter). A pose for the moment: one of its bases with any gesture, or one of\nits gestures on any base. Moments with neither come first.\n\n` +
  `| moment | beats | bases | gestures | wanted |\n|---|---|---|---|---|\n${rows.map(line).join('\n')}\n\n` +
  `## Wanted poses, in order\n\n| pose | what | beats (its busiest moment) | until it exists |\n|---|---|---|---|\n` +
  Object.entries(index.wanted).map(([n, w]) => `| ${n} | ${w.desc} | ${w.use.map((t) => count[t] || 0).reduce((a, b) => Math.max(a, b), 0)} | ${w.until} |`).join('\n') +
  `\n\n## Asked for by panels\n\n${needs.length ? needs.map((n) => `- ${n}`).join('\n') : '(none)'}\n`;

writeOut('docs/issues/missing-poses.md', md);
console.log('docs/issues/missing-poses.md');
for (const r of rows.filter((r) => !r.any)) console.log(`  no pose: ${r.tag} (${r.n} beats)`);

if (showScenes) {
  console.log('');
  for (const s of scenes.filter((s) => !only || s.id.startsWith(only))) {
    const tags = tagsOf(s.what);
    const bs = [...new Set(tags.flatMap((t) => halvesFor('bases', t)))], gs = [...new Set(tags.flatMap((t) => halvesFor('gestures', t)))];
    const want = [...new Set(tags.flatMap(wantedFor))];
    console.log(`${s.id}  ${s.what.replace(/\*\*/g, '').slice(0, 90)}`);
    console.log(`       moments:  ${tags.join(', ') || '-'}`);
    console.log(`       bases:    ${bs.join(', ') || 'step'}`);
    console.log(`       gestures: ${gs.join(', ') || 'hang'}${want.length ? `   (wanted: ${want.join(', ')})` : ''}`);
  }
}
