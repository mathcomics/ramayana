// Held props: one file per weapon in data/props/held/ (sword.svg,
// club.svg, bow.svg), each with a layer "base" (everyone's) and optional
// layers named by a character id (that character's own version).
//
//   node tools/import-held.mjs   ->  data/held.json
//
// Each layer: the drawing, plus a path labelled `line` (not drawn; sword
// and club: straight, grip -> tip; bow: the curve, top tip -> bottom tip)
// and, for the bow, a circle labelled `grip`. The pose places the line in
// the hand; the drawing's own line sets the weapon's size (100 px = 1
// head-unit), so each version can have its own length.
//
// Everything is stored in the line's own frame, in head-units: origin at
// the grip, +x along the line (sword, club: toward the tip; bow: toward the
// top tip), +y to the line's right (bow: the belly side). Curves and
// colours are kept; the drawing is only moved and turned.
import { parse, serialize, label } from './svg.mjs';
import { read, writeOut } from './lib.mjs';
import { mm, ap, parseTransform, pathPolys } from './svg-geom.mjs';

const KINDS = ['sword', 'club', 'bow'];
const K = 100, r4 = (v) => Math.round(v * 1e4) / 1e4;
const I = [1, 0, 0, 1, 0, 0];

// layers -> { name: { node, M (ancestors' transform incl. the layer's) } }
function layers(file) {
  const out = {};
  const walk = (n, M) => {
    for (const c of n.children || []) {
      if (c.tag !== 'g' && c.tag !== 'svg') continue;
      const M2 = c.attrs.transform ? mm(M, parseTransform(c.attrs.transform)) : M;
      if (c.attrs['inkscape:groupmode'] === 'layer' || c.tag === 'g' && label(c) && !out[label(c)] && n.tag === 'svg') out[label(c)] = { node: c, M: M2 };
      else walk(c, M2);
    }
  };
  walk(parse(read(file)), I);
  return out;
}
// the `line` path's points and the `grip` anchor of a layer, in file px
function refOf(L, where) {
  let pts = null, grip = null;
  const walk = (n, M) => {
    for (const c of n.children || []) {
      if (!c.tag) continue;
      const M2 = c.attrs.transform ? mm(M, parseTransform(c.attrs.transform)) : M;
      if (label(c) === 'line' && c.tag === 'path') {
        const polys = pathPolys(c.attrs.d);
        // a two-point line: its numbers as they stand (pathPolys keeps outlines only)
        const raw = polys.length ? polys.flat() : (() => { const n = (c.attrs.d.match(/-?\d*\.?\d+(?:e-?\d+)?/g) || []).map(Number); return [[n[0], n[1]], [n[n.length - 2], n[n.length - 1]]]; })();
        pts = raw.map((p) => ap(M2, p));
      }
      else if (label(c) === 'grip' && c.tag === 'circle') grip = ap(M2, [+c.attrs.cx, +c.attrs.cy]);
      else if (c.tag === 'g') walk(c, M2);
    }
  };
  walk(L.node, L.M);
  if (!pts) throw new Error(`${where}: no path labelled "line"`);
  return { a: pts[0], b: pts[pts.length - 1], pts, grip };
}
const sub = (p, q) => [p[0] - q[0], p[1] - q[1]];
// the frame of a line: origin at the grip, x along it (start -> end for a
// sword, end -> start for a bow, so +x points at the top tip)
function frameOf(ref, kind) {
  const o = kind === 'bow' ? ref.grip : ref.a;
  if (!o) throw new Error(`${kind}: the bow line needs a "grip" anchor`);
  const d = kind === 'bow' ? sub(ref.a, ref.b) : sub(ref.b, ref.a), len = Math.hypot(...d);
  const ux = [d[0] / len, d[1] / len], uy = [-ux[1], ux[0]];
  // file point -> line frame (head-units)
  const to = (p) => { const v = sub(p, o); return [(v[0] * ux[0] + v[1] * ux[1]) / K, (v[0] * uy[0] + v[1] * uy[1]) / K]; };
  // as a matrix: rows ux, uy, scaled, origin moved
  const M = [ux[0] / K, uy[0] / K, ux[1] / K, uy[1] / K, -(o[0] * ux[0] + o[1] * ux[1]) / K, -(o[0] * uy[0] + o[1] * uy[1]) / K];
  return { to, M, len: len / K };
}

const ids = new Set(JSON.parse(read('data/characters.json')).characters.map((c) => c.id));
const held = {};
for (const kind of KINDS) {
  const L = layers(`data/props/held/${kind}.svg`);
  if (!L.base) throw new Error(`${kind}.svg: no layer "base"`);
  held[kind] = {};
  for (const [name, layer] of Object.entries(L)) {
    if (name !== 'base' && !ids.has(name)) { console.warn(`  ! ${kind}.svg: layer "${name}" is not a character id; skipped`); continue; }
    const ref = refOf(layer, `${kind}.svg ${name}`), F = frameOf(ref, kind);
    const M = mm(F.M, layer.M);
    const body = layer.node.children.filter((c) => c.tag && !['line', 'grip'].includes(label(c))).map(serialize).join('');
    held[kind][name] = {
      svg: `<g transform="matrix(${M.map(r4).join(' ')})">${body}</g>`,
      tips: [ref.a, ref.b].map(F.to).map((p) => p.map(r4)),
      pts: ref.pts.map(F.to).map((p) => p.map(r4)),
    };
  }
}
console.log(writeOut('data/held.json', JSON.stringify({ _doc: 'Generated by tools/import-held.mjs from data/props/held/<kind>.svg; do not edit. Per kind: base and character versions. Line frame: head-units, origin at the grip, +x along the line (sword, club: to the tip; bow: to the top tip), +y the belly side. tips: the line ends (sword, club: grip, tip; bow: top, bottom).', ...held }, null, 1)));
console.log(KINDS.map((k) => `${k}: ${Object.keys(held[k]).join(', ')}`).join('; '));
