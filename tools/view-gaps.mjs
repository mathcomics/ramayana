// Which head views each character has drawn or missing, and which panel
// heads use a view that is not drawn yet -> docs/issues/missing-views.md
// (docs/proposals/2026-11-12-head-rendering-survey.md).
//
//   node tools/view-gaps.mjs
import { join } from 'node:path';
import { root, writeOut, loadAssets, loadSections } from './lib.mjs';
import { readFile } from './faces-lib.mjs';
import { renderPanel } from '../src/scene.js';
import { INTENDED_VIEWS } from '../src/headturn.js';

const A = loadAssets();
const cast = A.characters.characters;
const F = A.faces.faces;
const NAMES = { front: 'front', quarter: '3/4 (30°)', side: 'side', 'back-view': 'back', 'front-down': 'down 40°', top: 'top (down 90°)' };
const intended = (c) => (c.sideOnly ? ['side'] : INTENDED_VIEWS);
const state = (c, v) => (!intended(c).includes(v) ? '' : !F[c.id]?.[v] ? 'missing' : 'drawn');

// panel heads by the view they want
const uses = new Map();     // `${character} ${view}` -> [panel ids]
for (const sec of loadSections()) for (const { id, def } of sec.panels) {
  const { heads } = renderPanel(def, A, { id });
  for (const h of heads || []) {
    const k = `${h.character} ${h.want}`;
    if (!uses.has(k)) uses.set(k, []);
    uses.get(k).push(id);
  }
}
const used = (c, v) => uses.get(`${c.id} ${v}`) || [];

let md = `# Missing head views

Generated by \`node tools/view-gaps.mjs\` — do not edit. A head is drawn as
the nearest of its character's drawn views
(\`docs/proposals/2026-11-12-head-rendering-survey.md\`).
**missing**: no drawing, the nearest drawn view stands in. Side-only
characters (\`sideOnly\` in \`data/characters.json\`) have the side view only.

## By character

| Character | ${INTENDED_VIEWS.map((v) => NAMES[v]).join(' | ')} |
|---|${INTENDED_VIEWS.map(() => '---').join('|')}|
`;
for (const c of cast) md += `| ${c.id} | ${INTENDED_VIEWS.map((v) => state(c, v) || '·').join(' | ')} |\n`;

const todo = [];
for (const c of cast) for (const v of intended(c)) {
  const st = state(c, v);
  if (st === 'drawn') continue;
  todo.push({ c, v, st, panels: used(c, v) });
}
todo.sort((a, b) => b.panels.length - a.panels.length || a.c.id.localeCompare(b.c.id));
md += `
## To draw (${todo.length}), most used first

| Character | View | State | Panel heads using it |
|---|---|---|---|
`;
for (const t of todo) md += `| ${t.c.id} | ${NAMES[t.v]} | ${t.st} | ${t.panels.length ? t.panels.join(', ') : '—'} |\n`;

md += `
## Bases

The base faces (\`data/faces/base/\`): the views with a face, and the views
with only mouths (quarter, front-down: a character takes them unless it
draws its own). A character's view the base has no face for is the whole
head, drawn in the character's file.

| Base | Face | Mouths only |
|---|---|---|
`;
for (const sp of ['male', 'female', 'monkey']) {
  const { face, mouths } = baseViews(sp);
  md += `| ${sp} | ${face.join(', ')} | ${mouths.join(', ') || '—'} |\n`;
}
// a base draws a view's face when it has a skin layer (as composeFaces
// reads it); mouths only: mouths and no skin
function baseViews(sp) {
  const B = readFile(join(root, 'data/faces/base', `${sp}.svg`));
  const face = INTENDED_VIEWS.filter((v) => B[v]?.layers.skin);
  const mouths = INTENDED_VIEWS.filter((v) => !B[v]?.layers.skin && B[v]?.layers['mouth-1']);
  return { face, mouths };
}
writeOut('docs/issues/missing-views.md', md);
console.log(`docs/issues/missing-views.md: ${todo.length} view(s) to draw`);
