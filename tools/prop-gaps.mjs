// Which props the panels use that have no drawn art, and every prop wish
// from the panels' needs -> docs/issues/missing-props.md (for the sessions
// that draw and import props).
//
//   node tools/prop-gaps.mjs
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { root, writeOut, loadSections } from './lib.mjs';

const used = new Map();   // prop id -> Set of panel ids
const wishes = new Map(); // needs text ("prop: ...") -> Set of panel ids
for (const sec of loadSections()) {
  for (const { id, def } of sec.panels) {
    for (const p of [...(def.figures ?? []), ...(def.props ?? [])]) {
      if (!p.prop) continue;
      if (!used.has(p.prop)) used.set(p.prop, new Set());
      used.get(p.prop).add(id);
    }
    for (const n of def.needs ?? []) {
      if (!/^prop:/.test(n)) continue;
      if (!wishes.has(n)) wishes.set(n, new Set());
      wishes.get(n).add(id);
    }
  }
}

const drawn = (id) => existsSync(join(root, `data/props/${id}.svg`));
const missing = [...used.keys()].filter((id) => !drawn(id)).sort();
const have = [...used.keys()].filter(drawn).sort();
const ids = (set) => [...set].sort().join(', ');

let md = `# Missing props

Generated by \`node tools/prop-gaps.mjs\` from the panels. Do not edit by
hand; rerun it after changing panels or adding prop art. A prop is drawn
when \`data/props/<id>.svg\` exists (100 px = 1 head-unit, size from the
viewBox, optional \`anchors\` group with a \`seat\`; see
docs/design/panels.md, Props); until then the renderer shows a placeholder
box from \`data/props.json\`. Held props (sword, club, bow) live in
\`data/props/held/\` instead and are imported by \`tools/import-held.mjs\`.

## Placeholder props (used by panels, no drawn art)

| prop | panels |
|---|---|
`;
for (const id of missing) md += `| ${id} | ${ids(used.get(id))} |\n`;
md += `\n## Prop wishes from the panels' needs

What the panels say they want, in their own words (sizes and such in
docs/design/panel-writing.md, Lessons).

| need | panels |
|---|---|
`;
for (const [n, set] of [...wishes.entries()].sort((a, b) => a[0].localeCompare(b[0]))) md += `| ${n.replace(/\|/g, '\\|')} | ${ids(set)} |\n`;
md += `\n## Drawn props in use\n\n${have.join(', ')}\n`;

const out = writeOut('docs/issues/missing-props.md', md);
console.log(`${missing.length} placeholder props, ${wishes.size} wishes, ${have.length} drawn -> ${out}`);
